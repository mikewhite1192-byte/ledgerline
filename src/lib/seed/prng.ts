// Deterministic randomness for the seed: the same seed text always gives the same numbers and
// the same ids, on any machine and any Node version. mulberry32 (public domain) seeded with the
// 32-bit FNV-1a hash of the text. No library, so an upgrade can never change the demo data.

export function fnv1a32(text: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash >>> 0;
}

export class Rng {
  private state: number;

  constructor(seedText: string) {
    this.state = fnv1a32(seedText);
  }

  // A whole number in [0, 2^32).
  nextUint32(): number {
    this.state = (this.state + 0x6d2b79f5) >>> 0;
    let t = this.state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return (t ^ (t >>> 14)) >>> 0;
  }

  // A whole number from lo to hi, both included.
  int(lo: number, hi: number): number {
    if (!Number.isSafeInteger(lo) || !Number.isSafeInteger(hi) || hi < lo || hi - lo >= 2 ** 32) {
      throw new RangeError("int range is not valid");
    }
    return lo + Math.floor((this.nextUint32() / 2 ** 32) * (hi - lo + 1));
  }

  // true with probability num / den.
  chance(num: number, den: number): boolean {
    return this.int(1, den) <= num;
  }

  pick<T>(items: readonly T[]): T {
    if (items.length === 0) throw new RangeError("nothing to pick from");
    return items[this.int(0, items.length - 1)];
  }

  // A shuffled copy (Fisher-Yates).
  shuffle<T>(items: readonly T[]): T[] {
    const out = [...items];
    for (let i = out.length - 1; i > 0; i--) {
      const j = this.int(0, i);
      [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
  }

  // One value, chosen by whole-number weights.
  weighted<T>(entries: readonly (readonly [T, number])[]): T {
    const total = entries.reduce((n, [, w]) => n + w, 0);
    if (!Number.isSafeInteger(total) || total <= 0) throw new RangeError("weights are not valid");
    let roll = this.int(1, total);
    for (const [value, weight] of entries) {
      roll -= weight;
      if (roll <= 0) return value;
    }
    throw new RangeError("weights are not valid");
  }

  // A version 4 UUID from 16 generated bytes: valid, and the same on every run.
  uuid(): string {
    const bytes: number[] = [];
    for (let i = 0; i < 4; i++) {
      const n = this.nextUint32();
      bytes.push(n >>> 24, (n >>> 16) & 0xff, (n >>> 8) & 0xff, n & 0xff);
    }
    bytes[6] = (bytes[6] & 0x0f) | 0x40;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    const hex = bytes.map((b) => b.toString(16).padStart(2, "0")).join("");
    const parts = [hex.slice(0, 8), hex.slice(8, 12), hex.slice(12, 16), hex.slice(16, 20)];
    return `${parts.join("-")}-${hex.slice(20)}`;
  }
}
