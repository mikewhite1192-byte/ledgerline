// The spend ledger: one model_calls row per call and the global counter in ops.ai_spend
// (db/migrations/0002_ai_spend.sql, 0003_model_calls.sql). Reserve before the call, settle after, each
// in its own short transaction: a model call never sits inside a database transaction. Reads use
// SELECT only and writes check rows affected, because the Data API returns no rows for
// INSERT or UPDATE ... RETURNING.

type Counter = {
  spent_nanocents: number;
  reserved_nanocents: number;
  calls: number;
  wonder_spent_nanocents: number;
  wonder_reserved_nanocents: number;
};

const COUNTER_COLUMNS =
  "spent_nanocents, reserved_nanocents, calls, wonder_spent_nanocents, wonder_reserved_nanocents";

function checked(counter: Counter | undefined): Counter {
  // A missing row or a value that is not a safe integer is unknown, never zero.
  if (
    !counter ||
    !Number.isSafeInteger(counter.spent_nanocents) ||
    !Number.isSafeInteger(counter.reserved_nanocents) ||
    !Number.isSafeInteger(counter.calls) ||
    !Number.isSafeInteger(counter.wonder_spent_nanocents) ||
    !Number.isSafeInteger(counter.wonder_reserved_nanocents)
  ) {
    throw new DbError("unknown");
  }
  return counter;
}

export type Reservation = {
  // Generated by the app before the call: the row's primary key, so one call is one row.
  callId: string;
  target: AiTarget;
  provider: AiProvider;
  model: string;
  kind: AiCallKind;
  purpose: string;
  reasoningEffort: AiReasoningEffort | null;
  traceId: string | null;
  reserveNanocents: number;
  capNanocents: number;
  // Required for a wonder reservation, ignored otherwise.
  wonderCapNanocents: number | null;
  // The job's hourly allowance (./watch.ts).
  jobCapNanocents: number;
  // When the call is reserved, as an ISO instant: the row's created_at and the end of the job's
  // window. Null is the database clock, which is what production passes; tests pass an instant.
  at: string | null;
};

// What the cap test reads from a reservation.
export type CapCheck = Pick<
  Reservation,
  "target" | "reserveNanocents" | "capNanocents" | "wonderCapNanocents"
>;

// The cap test reserve() makes under the counter's lock: true when the reservation would take the
// overall spend past its cap, or a wonder reservation the Wonder spend past the Wonder cap (a
// missing Wonder cap counts as zero, so it refuses). Exported so a read-only check made before a
// call (spendRoom in ./index.ts) runs this same test and cannot drift from it.
export function overCap(spend: Spend, r: CapCheck): boolean {
  if (spend.spentNanocents + spend.reservedNanocents + r.reserveNanocents > r.capNanocents) {
    return true;
  }
  return (
    r.target === "wonder" &&
    spend.wonderSpentNanocents + spend.wonderReservedNanocents + r.reserveNanocents >
      (r.wonderCapNanocents ?? 0)
  );
}

// The counter's row lock serializes reservations: a second one waits for the first to commit,
// then sees its reservation. Two calls can never both pass a cap. A wonder reservation must pass
// the overall cap and the Wonder cap, both read under the same lock, and then its job's hourly
// allowance (./watch.ts), under that lock too. Throws AiError("cap") with nothing written,
// AiError("job_cap") with nothing written to the ledger (the job's one alert row commits first),
// AiError("not_configured") for a wonder reservation without a Wonder cap, the tenant module's
// ForbiddenError when the session has no membership, or DbError when the job's spend cannot be
// read (fail closed). check, when given, is the caller's own limit, run in this same transaction
// right after the membership check and before the counter's row is locked (so any lock it takes
// comes first): the row this reservation writes uses up what it counted, and the next check made
// after this commits sees it. Whatever it throws, nothing is written. Only the rate lookup passes
// one.
export async function reserve(
  db: TenantDb,
  session: Session,
  r: Reservation,
  check?: (q: Queryable) => Promise<void>,
): Promise<void> {
  const wonder = r.target === "wonder";
  if (wonder && r.wonderCapNanocents === null) throw new AiError("not_configured");
  const verdict = await db.withTenant(session.tenantId, async (q): Promise<JobVerdict> => {
    await assertMembership(q, session);
    if (check) await check(q);
    const counter = checked(
      (
        await q.query<Counter>(
          `SELECT ${COUNTER_COLUMNS} FROM ops.ai_spend WHERE id = 1 FOR UPDATE`,
        )
      )[0],
    );
    if (overCap(spendOf(counter), r)) throw new AiError("cap");
    // Returned, not thrown: a throw would roll back the alert the watch just wrote.
    const job = await checkJob(q, {
      traceId: r.traceId,
      purpose: r.purpose,
      at: r.at,
      jobCapNanocents: r.jobCapNanocents,
      reserveNanocents: r.reserveNanocents,
    });
    if (job === "job_cap") return "job_cap";
    const inserted = await q.execute(
      `INSERT INTO model_calls (id, tenant_id, target, provider, model, kind, purpose,
                                reasoning_effort, trace_id, status, reserved_nanocents, created_at)
       VALUES (CAST($1 AS uuid), current_tenant_id(), $2, $3, $4, $5, $6, $7, CAST($8 AS uuid),
               'reserved', CAST($9 AS bigint), COALESCE(CAST($10 AS timestamptz), now()))`,
      [
        r.callId,
        r.target,
        r.provider,
        r.model,
        r.kind,
        r.purpose,
        r.reasoningEffort,
        r.traceId,
        r.reserveNanocents,
        r.at,
      ],
    );
    const updated = await q.execute(
      `UPDATE ops.ai_spend
          SET reserved_nanocents = reserved_nanocents + CAST($1 AS bigint),
              wonder_reserved_nanocents = wonder_reserved_nanocents + CAST($2 AS bigint),
              updated_at = now()
        WHERE id = 1`,
      [r.reserveNanocents, wonder ? r.reserveNanocents : 0],
    );
    if (inserted !== 1 || updated !== 1) throw new DbError("unknown");
    return "ok";
  });
  if (verdict === "job_cap") throw new AiError("job_cap");
}

// answered: the provider reported what the price needs, so the reservation is released and the
// real cost spent.
// refused: never charged, so the reservation is released and nothing spent.
// unknown: the reservation stays counted against the cap, forever (there is no usage read-back).
// A timeout settles here as unknown with failure 'timeout'.
export type Settlement = { durationMs: number } & (
  | {
      kind: "answered";
      status: "ok" | "incomplete";
      // Token calls report usage; the others report units (audio seconds or images).
      usage: AiUsage | null;
      units: number | null;
      costNanocents: number;
      upstreamId: string | null;
      httpStatus: number;
    }
  | { kind: "refused"; category: AiFailureCategory; httpStatus: number }
  | { kind: "unknown"; category: AiFailureCategory; httpStatus: number | null }
);

// Settles one reserved row. The dedupe is the row's status: only a row still 'reserved' is
// settled, so a second settle of the same call changes nothing and returns false. The amount
// released is the one the row recorded, not one the caller passes, and the Wonder counters move
// only for a row whose target is wonder. No membership check: the call already happened, and
// refusing to record it would only leave its reservation counted.
export async function settle(
  db: TenantDb,
  session: Session,
  callId: string,
  s: Settlement,
): Promise<boolean> {
  return db.withTenant(session.tenantId, async (q) => {
    const [row] = await q.query<{ reserved_nanocents: number; target: string }>(
      `SELECT reserved_nanocents, target FROM model_calls
        WHERE id = CAST($1 AS uuid) AND status = 'reserved' FOR UPDATE`,
      [callId],
    );
    if (!row) return false;
    if (!Number.isSafeInteger(row.reserved_nanocents)) throw new DbError("unknown");
    if (answeredCostInvalid(s)) throw new DbError("unknown");

    const answered = s.kind === "answered" ? s : null;
    const updated = await q.execute(
      `UPDATE model_calls
          SET status = $2, failure = $3, cost_nanocents = CAST($4 AS bigint),
              input_tokens = CAST($5 AS integer), cached_tokens = CAST($6 AS integer),
              output_tokens = CAST($7 AS integer), reasoning_tokens = CAST($8 AS integer),
              upstream_id = $9, http_status = CAST($10 AS smallint),
              duration_ms = CAST($11 AS integer), units = CAST($12 AS integer), settled_at = now()
        WHERE id = CAST($1 AS uuid) AND status = 'reserved'`,
      [
        callId,
        answered ? answered.status : s.kind === "refused" ? "failed" : "unknown",
        s.kind === "answered" ? null : s.category,
        answered ? answered.costNanocents : s.kind === "refused" ? 0 : null,
        answered?.usage?.input ?? null,
        answered?.usage?.cached ?? null,
        answered?.usage?.output ?? null,
        answered?.usage?.reasoning ?? null,
        answered?.upstreamId ?? null,
        s.httpStatus,
        s.durationMs,
        answered?.units ?? null,
      ],
    );
    if (updated !== 1) throw new DbError("unknown");

    const release = s.kind === "unknown" ? 0 : row.reserved_nanocents;
    const spent = answered ? answered.costNanocents : 0;
    const wonder = row.target === "wonder";
    const counted = await q.execute(
      `UPDATE ops.ai_spend
          SET reserved_nanocents = reserved_nanocents - CAST($1 AS bigint),
              spent_nanocents = spent_nanocents + CAST($2 AS bigint),
              wonder_reserved_nanocents = wonder_reserved_nanocents - CAST($3 AS bigint),
              wonder_spent_nanocents = wonder_spent_nanocents + CAST($4 AS bigint),
              calls = calls + 1, updated_at = now()
        WHERE id = 1`,
      [release, spent, wonder ? release : 0, wonder ? spent : 0],
    );
    if (counted !== 1) throw new DbError("unknown");
    return true;
  });
}

// A cost the ledger cannot hold is never written: the row stays reserved, its reservation counted.
function answeredCostInvalid(s: Settlement): boolean {
  return (
    s.kind === "answered" &&
    (!Number.isSafeInteger(s.costNanocents) ||
      s.costNanocents < 0 ||
      (s.units !== null && (!Number.isSafeInteger(s.units) || s.units < 0)))
  );
}

export type Spend = {
  spentNanocents: number;
  reservedNanocents: number;
  calls: number;
  wonderSpentNanocents: number;
  wonderReservedNanocents: number;
};

function spendOf(counter: Counter): Spend {
  return {
    spentNanocents: counter.spent_nanocents,
    reservedNanocents: counter.reserved_nanocents,
    calls: counter.calls,
    wonderSpentNanocents: counter.wonder_spent_nanocents,
    wonderReservedNanocents: counter.wonder_reserved_nanocents,
  };
}

// The global counter. Any app transaction may read it; it holds no tenant's data.
export async function readSpend(q: Queryable): Promise<Spend> {
  return spendOf(
    checked(
      (await q.query<Counter>(`SELECT ${COUNTER_COLUMNS} FROM ops.ai_spend WHERE id = 1`))[0],
    ),
  );
}

export type CallRow = {
  id: string;
  target: string;
  kind: string;
  purpose: string;
  model: string;
  reasoning_effort: string | null;
  status: string;
  failure: string | null;
  input_tokens: number | null;
  output_tokens: number | null;
  reasoning_tokens: number | null;
  units: number | null;
  cost_nanocents: number | null;
  duration_ms: number | null;
  upstream_id: string | null;
  created_utc: string;
};

// This tenant's newest calls (row-level security limits them to the transaction's tenant).
export async function readRecentCalls(q: Queryable, limit: number): Promise<CallRow[]> {
  return q.query<CallRow>(
    `SELECT id, target, kind, purpose, model, reasoning_effort, status, failure, input_tokens,
            output_tokens, reasoning_tokens, units, cost_nanocents, duration_ms, upstream_id,
            to_char(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') AS created_utc
       FROM model_calls
      WHERE tenant_id = current_tenant_id()
      ORDER BY created_at DESC
      LIMIT $1`,
    [limit],
  );
}
