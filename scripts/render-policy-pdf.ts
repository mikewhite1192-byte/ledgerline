import { createWriteStream, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import PDFDocument from "pdfkit";

// npm run policy:pdf
//
// Renders every sample pay policy for the onboarding demo from its tracked text,
// src/lib/seed/policy/<name>.md, to public/samples/policy/<name>.pdf, where a download link reads
// it with no build step, and writes the same bytes into src/lib/policy-onboard/samples.generated.ts
// for the sample route (the server reads no file from public/ at run time). The text is the
// contract, not the bytes: "#" lines are headings and blank lines split paragraphs. Every page
// carries a SAMPLE header and a footer saying the carrier is invented. Built-in Helvetica, so no
// font files; the creation date is fixed, so the same text renders the same file.

const SOURCE_DIR = join(process.cwd(), "src", "lib", "seed", "policy");
const TARGET_DIR = join(process.cwd(), "public", "samples", "policy");
const MODULE = join(process.cwd(), "src", "lib", "policy-onboard", "samples.generated.ts");
const HEADER = "SAMPLE";
const FOOTER =
  "Fictitious carrier created for a software demonstration. Not a real company or policy.";
const CREATED = new Date("2026-10-27T00:00:00Z");

type Block = { heading: boolean; text: string };

// Paragraphs are split by blank lines; the lines inside one are joined with a space.
function blocksOf(text: string): Block[] {
  return text
    .split(/\n\s*\n/)
    .map((chunk) => chunk.split("\n").map((line) => line.trim()).join(" ").trim())
    .filter((chunk) => chunk.length > 0)
    .map((chunk) =>
      chunk.startsWith("#")
        ? { heading: true, text: chunk.replace(/^#+\s*/, "") }
        : { heading: false, text: chunk },
    );
}

async function render(source: string, target: string): Promise<number> {
  const blocks = blocksOf(readFileSync(source, "utf8"));
  if (blocks.length === 0 || !blocks[0].heading) throw new Error(`${basename(source)} has no title line`);
  const doc = new PDFDocument({
    size: "LETTER",
    margins: { top: 72, bottom: 72, left: 72, right: 72 },
    bufferPages: true,
    info: {
      Title: `${blocks[0].text} (SAMPLE)`,
      Subject: FOOTER,
      CreationDate: CREATED,
      ModDate: CREATED,
    },
  });
  const out = createWriteStream(target);
  const done = new Promise<void>((resolve, reject) => {
    out.on("finish", resolve);
    out.on("error", reject);
  });
  doc.pipe(out);

  blocks.forEach((block, i) => {
    if (block.heading) {
      if (i > 0) doc.moveDown(0.5);
      doc.font("Helvetica-Bold").fontSize(i === 0 ? 16 : 12);
      doc.text(block.text, { paragraphGap: 4 });
    } else {
      doc.font("Helvetica").fontSize(10.5).text(block.text, { lineGap: 2, paragraphGap: 6 });
    }
  });

  // The header and footer sit in the margins, so the bottom margin is lifted while they are
  // drawn; otherwise the footer would start a new page.
  const pages = doc.bufferedPageRange();
  for (let n = pages.start; n < pages.start + pages.count; n++) {
    doc.switchToPage(n);
    const { width, height, margins } = doc.page;
    const box = { width: width - margins.left - margins.right, align: "center" as const };
    const bottom = margins.bottom;
    doc.page.margins.bottom = 0;
    doc.font("Helvetica-Bold").fontSize(14).fillColor("#b42318");
    doc.text(HEADER, margins.left, 36, { ...box, lineBreak: false });
    doc.font("Helvetica").fontSize(8).fillColor("#555555");
    doc.text(FOOTER, margins.left, height - 44, { ...box, lineBreak: false });
    doc.page.margins.bottom = bottom;
  }

  doc.end();
  await done;
  console.log(`wrote ${target} (${blocks.length} blocks, ${pages.count} pages)`);
  return pages.count;
}

async function main(): Promise<void> {
  const names = readdirSync(SOURCE_DIR)
    .filter((f) => f.endsWith(".md"))
    .map((f) => f.slice(0, -3))
    .sort();
  mkdirSync(TARGET_DIR, { recursive: true });
  const entries: string[] = [];
  for (const name of names) {
    if (!/^[a-z0-9-]{3,60}$/.test(name)) throw new Error(`${name}.md is not a plain sample name`);
    const target = join(TARGET_DIR, `${name}.pdf`);
    await render(join(SOURCE_DIR, `${name}.md`), target);
    entries.push(`  "${name}": "${readFileSync(target).toString("base64")}",`);
  }
  writeFileSync(
    MODULE,
    [
      "// Generated by npm run policy:pdf from src/lib/seed/policy/*.md. Do not edit by hand.",
      "// The sample policies' PDF bytes, base64, the same bytes as public/samples/policy/<name>.pdf",
      "// (policy.test.ts checks both). Synthetic documents for invented carriers.",
      "",
      "export const SAMPLE_POLICY_PDFS: Readonly<Record<string, string>> = {",
      ...entries,
      "};",
      "",
    ].join("\n"),
  );
  console.log(`wrote ${MODULE} (${entries.length} samples)`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : String(err));
  process.exit(1);
});
